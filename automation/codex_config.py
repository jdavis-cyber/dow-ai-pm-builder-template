#!/usr/bin/env python3
"""Generate Codex sandbox configuration from provider-neutral gate authority.

Operator usage: python3 automation/codex_config.py codex-config
End active sessions before refreshing, then start a new Codex session.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import sys
import tempfile

import gatekeeper

CODEX_CONFIG_PATH = Path(".codex/config.toml")
# Preserve the ownership marker so existing generated configs can be refreshed.
CODEX_CONFIG_HEADER = "# Generated by gatekeeper.py codex-config; Human Director owned.\n"


def codex_config_text(authorized: bool) -> str:
    """Native Codex filesystem permissions; no prompt or shell parsing involved.

    writable_roots is additive: a planning-only list cannot exclude src/ when
    the cwd is the project root. Keep the entire project read-only until the
    Human Director grants authority. This also overrides legacy user defaults.
    """
    lines = [
        CODEX_CONFIG_HEADER.rstrip(),
        f'approval_policy = "{"never" if authorized else "on-request"}"',
        f'sandbox_mode = "{"workspace-write" if authorized else "read-only"}"',
        '\n[sandbox_workspace_write]',
        'writable_roots = []',
        'network_access = false',
        'exclude_tmpdir_env_var = true',
        'exclude_slash_tmp = true',
    ]
    return "\n".join(lines) + "\n"


def codex_config() -> int:
    """Operator command: snapshot authority into a protected Codex config.

    Run outside the agent session, then start a new session. Sandbox settings
    are session boundaries, not a live revocation service.
    """
    config = gatekeeper.ROOT / CODEX_CONFIG_PATH
    if config.parent.is_symlink() or config.is_symlink():
        print("REFUSAL: Codex configuration must not be a symlink")
        return 2
    if config.exists() and not config.read_text().startswith(CODEX_CONFIG_HEADER):
        print(f"REFUSAL: existing {CODEX_CONFIG_PATH.as_posix()} is not gatekeeper-owned")
        return 2
    problem = ""
    try:
        state = gatekeeper.load_state()
        if not isinstance(state, dict):
            raise ValueError("gate state must be an object")
        authorized = gatekeeper.implementation_permission(state)
        # Do not authorize a project whose conventional directories escape it.
        for prefix in (*gatekeeper.PLANNING_PREFIXES, *gatekeeper.PROTECTED_SOURCE_PREFIXES):
            if prefix.endswith("/") and (gatekeeper.ROOT / prefix.rstrip("/")).is_symlink():
                raise ValueError(f"writable directory {prefix} must not be a symlink")
    except (OSError, ValueError, TypeError) as exc:
        authorized = False
        problem = str(exc)
    text = codex_config_text(authorized)
    config.parent.mkdir(parents=True, exist_ok=True)
    # Atomic replacement prevents an interrupted refresh leaving a partial config.
    fd, temporary = tempfile.mkstemp(prefix=".gatekeeper-", dir=config.parent)
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(text)
        os.replace(temporary, config)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    if problem:
        print(f"REFUSAL: {problem}; Codex config reset to read-only")
        return 2
    print(f"Codex source access: {'write' if authorized else 'read-only'}; start a new session")
    return 0


def refresh_if_present() -> int:
    """Refresh an existing generated configuration after operator sign-off."""
    if (gatekeeper.ROOT / CODEX_CONFIG_PATH).exists():
        return codex_config()
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("codex-config", help="operator: refresh Codex permissions, then restart Codex")
    parser.parse_args(argv)
    return codex_config()


if __name__ == "__main__":
    sys.exit(main())
